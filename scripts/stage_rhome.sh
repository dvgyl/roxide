#!/usr/bin/env bash
# Stage a clean-room Roxide R_HOME directory tree (ADR-0020).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROFILE="${1:-debug}"
RHOME="${2:-$ROOT/target/rhome}"

BIN_SRC="$ROOT/target/$PROFILE/roxide"
INC_SRC="$ROOT/crates/roxide-capi/include"
SHLIB_MK_SRC="$ROOT/share/make/shlib.mk"

mkdir -p "$RHOME/bin" "$RHOME/include" "$RHOME/lib" "$RHOME/etc" "$RHOME/share/make"

if [ -x "$BIN_SRC" ]; then
  cp -f "$BIN_SRC" "$RHOME/bin/roxide"
  ln -sf roxide "$RHOME/bin/R"
  ln -sf roxide "$RHOME/bin/Rscript"
fi

if [ -d "$INC_SRC" ]; then
  cp -R "$INC_SRC"/. "$RHOME/include/"
fi

if [ -f "$SHLIB_MK_SRC" ]; then
  cp -f "$SHLIB_MK_SRC" "$RHOME/share/make/shlib.mk"
fi

UNAME_S="$(uname -s)"
if [ "$UNAME_S" = "Darwin" ]; then
  LIBR_EXT="dylib"
  SHLIB_LDFLAGS="-dynamiclib -Wl,-headerpad_max_install_names -undefined dynamic_lookup"
  BLAS_LIBS="-framework Accelerate"
  LAPACK_LIBS="-framework Accelerate"
else
  LIBR_EXT="so"
  SHLIB_LDFLAGS="-shared"
  BLAS_LIBS="-lopenblas"
  LAPACK_LIBS="-lopenblas"
fi

cat > "$RHOME/etc/Makeconf" <<EOF
# Generated by Roxide scripts/stage_rhome.sh (ADR-0020)
R_HOME = $RHOME
R_INCLUDE_DIR = $RHOME/include
R_SHARE_DIR = $RHOME/share
CC = ${CC:-clang}
CXX = ${CXX:-clang++}
CXX11 = ${CXX:-clang++}
CXX14 = ${CXX:-clang++}
CXX17 = ${CXX:-clang++}
CXX20 = ${CXX:-clang++}
CXX11STD = -std=gnu++11
CXX14STD = -std=gnu++14
CXX17STD = -std=gnu++17
CXX20STD = -std=gnu++20
FC = ${FC:-}
CFLAGS = -g -O2
CXXFLAGS = -g -O2
CPICFLAGS = -fPIC
CXXPICFLAGS = -fPIC
FPICFLAGS = -fPIC
CPPFLAGS = -I$RHOME/include
SHLIB_EXT = .so
SHLIB_LD = \$(CC)
SHLIB_CXXLD = \$(CXX)
SHLIB_LDFLAGS = $SHLIB_LDFLAGS
SHLIB_CXXLDFLAGS = $SHLIB_LDFLAGS
LIBR = -L$RHOME/lib -lR
BLAS_LIBS = $BLAS_LIBS
LAPACK_LIBS = $LAPACK_LIBS
FLIBS =
EOF

echo "Staged Roxide R_HOME at $RHOME (profile=$PROFILE, libR=libR.$LIBR_EXT)"
